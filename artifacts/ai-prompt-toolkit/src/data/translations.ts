export const TRANSLATIONS: Record<string, TranslationDict> = {
  hi: HI,
  es: ES,
  fr: FR,
  de: DE,
  ja: JA,
  zh: ZH,
  pt: PT,
  ar: AR,
};

export function translatePrompt(text: string, langId: string): string {
  const dict = TRANSLATIONS[langId];
  if (!dict) return text;

  let result = text;

  // Sort keys by length (longest first) to match multi-word phrases first
  const sortedKeys = Object.keys(dict).sort((a, b) => b.length - a.length);

  for (const phrase of sortedKeys) {
    const translation = dict[phrase];
    // Escape special regex characters in phrase
    const escaped = phrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const regex = new RegExp(`(?<!\\[)\\b${escaped}\\b(?!\\])`, "g");
    result = result.replace(regex, translation);
  }

  return result;
}
